// kit-skin (KS10 of the kit and stage build): skin and trim, the panes no other desk bundle rebuilt, by CSS alone (app/ui/desk-skin.css, kit.desk).
//
// desk-skin.css has two halves. The FIRST is generated from the old sheets by this file (--write); the second is written by hand.
//   the type floor (KS10.2)   every font-size the old sheets give the GM page (font-size, and the size inside a font shorthand), in the old cascade's own order
//                              (sorted by the old selector's weight, then by where it stood), at zero weight: under 12 px becomes 12, 12 to 13 becomes 12,
//                              13 to 15 becomes 14, 15 to 17 becomes 16, larger stays; a relative size becomes max(12px, size). Zero weight, so every
//                              other kit sheet (a rebuilt pane, a ui-* part) still wins; unlayered, so it beats the old sheets (layered once a kit token is on).
//                              Why all of them, not only the small ones: an unlayered rule beats a layered one whatever the weights, so a floor written only
//                              for `.chip` (11 px) would also beat an old `#gm-page .big.chip` (16 px). Writing every one, in order, keeps the old winner.
//   mono for keys and time     every font family the old sheets give the GM page, in the same order: mono becomes the text face unless the selector is a
//                              key, a time or code (KS10.2)
//   flat (KS10.1, KS10.4)      every box shadow, in the same order: an offset or blurred layer goes (the hard offset belongs to the Primary alone, and in
//                              Night the old one is orange); an inset line (an active underline) or a ring stays
//   no orange hover (KS10.3)   every old :hover rule that paints the accent (var(--accent), var(--on-accent)) paints the sunk ground and the ink instead;
//                              never on an element that is pressed, current, selected or on (its own colour stays)
// The second half gives the old .btn, .chip, .seg, .gm-btn and .hint the kit's ranks and trims each pane; it comes after, so it wins a tie.
//
//   node checks/runtime/kit-skin.e2e.mjs --write     rewrite the generated half from the old sheets (after an old sheet changes)
//   node checks/runtime/kit-skin.e2e.mjs             the static checks (the generated half is current; no !important, no @layer, every rule under
//                                                    :where(:root[data-kit~="desk"] ...)), then, with Playwright, the browser checks on the demo night
//   PW_MODULE=<path to playwright> [PW_CHANNEL=msedge] [PORT=9408] [SHOTS=<dir>] node checks/runtime/kit-skin.e2e.mjs
// The browser checks start the demo night (scripts/demo-night.mjs: the real Worker, pack and GM page, everything invented) on PORT, with wrangler's
// inspector on PORT + 20000, as the other browser checks do. No model, no key: the Anthropic keys are taken out of the environment.
