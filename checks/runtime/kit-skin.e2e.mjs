const inlineBlock = () => { const m = /<style>([\s\S]*?)<\/style>/.exec(read('index.html')); return m ? m[1] : ''; };
function stripComments(s) {
  let out = '', i = 0; const n = s.length;
  while (i < n) {
    const c = s[i];
    if (c === '/' && s[i + 1] === '*') { const e = s.indexOf('*/', i + 2); i = e < 0 ? n : e + 2; continue; }
    if (c === '"' || c === "'") { let j = i + 1; while (j < n && s[j] !== c) { if (s[j] === '\\') j++; j++; } out += s.slice(i, j + 1); i = j + 1; continue; }
    out += c; i++;
  }
  return out;
}
/* split on ch outside () [] and strings */
function splitTop(s, ch) {
  const out = []; let d = 0, cur = '', q = '';
  for (let i = 0; i < s.length; i++) {
    const c = s[i];
    if (q) { cur += c; if (c === '\\') { cur += s[++i] || ''; continue; } if (c === q) q = ''; continue; }
    if (c === '"' || c === "'") { q = c; cur += c; continue; }
    if (c === '(' || c === '[') d++; else if (c === ')' || c === ']') d--;
    if (c === ch && d === 0) { out.push(cur); cur = ''; } else cur += c;
  }
  out.push(cur);
  return out;
}
/* the style rules of a sheet: { ctx: [@media ... preludes], sels, decls: [{ prop, value, important }] }, in order; @font-face, @keyframes and the like skipped */
function parse(css) {
  const s = stripComments(css), rules = [];
  const close = (j) => {
    let d = 1, q = '';
    for (let k = j + 1; k < s.length; k++) {
      const c = s[k];
      if (q) { if (c === '\\') { k++; continue; } if (c === q) q = ''; continue; }
      if (c === '"' || c === "'") { q = c; continue; }
      if (c === '{') d++; else if (c === '}' && --d === 0) return k;
    }
    return s.length;
  };
  function block(i, ctx) {
    while (i < s.length) {
      while (i < s.length && /\s/.test(s[i])) i++;
      if (i >= s.length) return i;
      if (s[i] === '}') return i + 1;
      let j = i, d = 0, q = '';
      for (; j < s.length; j++) {
        const c = s[j];
        if (q) { if (c === '\\') { j++; continue; } if (c === q) q = ''; continue; }
        if (c === '"' || c === "'") { q = c; continue; }
        if (c === '(' || c === '[') d++; else if (c === ')' || c === ']') d--;
        else if (d === 0 && (c === '{' || c === ';' || c === '}')) break;
      }
      const prelude = s.slice(i, j).trim();
      if (s[j] === ';') { i = j + 1; continue; }
      if (s[j] === '}' || j >= s.length) return j + 1;
      if (prelude.startsWith('@')) {
        if (/^@(media|supports|container)\b/.test(prelude)) { i = block(j + 1, ctx.concat([prelude.replace(/\s+/g, ' ')])); continue; }
        i = close(j) + 1; continue;
      }
      const k = close(j), body = s.slice(j + 1, k);
      if (!body.includes('{')) {
        const decls = splitTop(body, ';').map((x) => x.trim()).filter(Boolean).map((x) => {
          const c = x.indexOf(':'); if (c < 0) return null;
          let value = x.slice(c + 1).trim(), important = false;
          const m = /!\s*important\s*$/i.exec(value); if (m) { important = true; value = value.slice(0, m.index).trim(); }
          return { prop: x.slice(0, c).trim().toLowerCase(), value, important };
        }).filter(Boolean);
        rules.push({ ctx, sels: splitTop(prelude, ',').map((x) => x.trim().replace(/\s+/g, ' ')).filter(Boolean), decls });
      }
      i = k + 1;
    }
    return i;
  }
  block(0, []);
  return rules;
}
const cmp = (x, y) => x[0] - y[0] || x[1] - y[1] || x[2] - y[2];
/* a selector's weight [ids, classes, types] */
function weight(sel) {
  let a = 0, b = 0, c = 0, i = 0;
  const most = (list) => splitTop(list, ',').map((x) => weight(x.trim())).reduce((m, x) => (cmp(x, m) > 0 ? x : m), [0, 0, 0]);
  while (i < sel.length) {
    const ch = sel[i];
    if (ch === '#' || ch === '.') { if (ch === '#') a++; else b++; i++; while (i < sel.length && /[\w\\-]/.test(sel[i])) i++; continue; }
    if (ch === '[') { b++; let d = 0; for (; i < sel.length; i++) { if (sel[i] === '[') d++; else if (sel[i] === ']' && --d === 0) { i++; break; } } continue; }
    if (ch === ':') {
      const el = sel[i + 1] === ':'; i += el ? 2 : 1;
      let nm = ''; while (i < sel.length && /[\w-]/.test(sel[i])) nm += sel[i++];
      let arg = null;
      if (sel[i] === '(') { let d = 0, j = i; for (; j < sel.length; j++) { if (sel[j] === '(') d++; else if (sel[j] === ')' && --d === 0) break; } arg = sel.slice(i + 1, j); i = j + 1; }
      nm = nm.toLowerCase();
      if (el || ['before', 'after', 'first-line', 'first-letter'].includes(nm)) { c++; continue; }
      if (nm === 'where') continue;
      if (['not', 'is', 'has', 'matches'].includes(nm)) { if (arg) { const w = most(arg); a += w[0]; b += w[1]; c += w[2]; } continue; }
      b++; continue;
    }
    if (/[a-zA-Z]/.test(ch)) { c++; while (i < sel.length && /[\w-]/.test(sel[i])) i++; continue; }
    i++;
  }
  return [a, b, c];
}
/* Does a selector belong to the GM page? Its classes and ids must appear in the GM page's own scripts (a prefix built in code counts), and it is
   not one of the other routes' (home, the schedule, the table, the phone's sheet, the #rules and #cast pages). Only to keep the file short:
   a selector that cannot match the GM page would do nothing there. */
const CORPUS = (() => {
  const out = [], skip = /^(display-page|tracker|schedule|season|campaign|crewsheet|lookbook-boot|sw|steps)\.js$/;
  const walk = (d) => {
    for (const e of fs.readdirSync(d, { withFileTypes: true }).sort((x, y) => (x.name < y.name ? -1 : 1))) {
      const p = path.join(d, e.name);
      if (e.isDirectory()) { if (!/^(checks|display|sheet|fonts|icons|ambient|media)$/.test(e.name)) walk(p); }
      else if (/\.js$/.test(e.name) && !skip.test(e.name)) out.push(fs.readFileSync(p, 'utf8'));
    }
  };
  walk(APP);
  return out.join('\n');
})();
function onGm(sel) {
  if (/[.#](hm|sc|tp|ds|nx|cs)-|#(table-page|rules-page|cast-page|stage|home|dossier|season)\b|\.hm\b|body\[data-mode="(?!gm)/.test(sel)) return false;
  for (const m of sel.matchAll(/[.#]([\w-]+)/g)) {
    const t = m[1]; if (CORPUS.includes(t)) continue;
    const cut = t.lastIndexOf('-'), pre = cut > 0 ? t.slice(0, cut + 1) : null;
    if (pre && (CORPUS.includes("'" + pre) || CORPUS.includes('"' + pre) || CORPUS.includes(' ' + pre + "'"))) continue;
    return false;
  }
  return true;
}
const SKIP = /(^|[\s>+~])(svg|text|tspan)\b|::?(-webkit-|-moz-|placeholder|selection|marker|backdrop|file-selector)/;
const PSEUDO = /(::?(before|after|first-line|first-letter))$/;
/* the scoped selector, at zero weight: a pseudo-element cannot sit inside :where(), so it stays outside (it weighs the same on every rule it is on) */
function scoped(sel) {
  const m = PSEUDO.exec(sel), pseudo = m ? m[1] : '', base = m ? sel.slice(0, -pseudo.length) : sel;
  const inner = /^(html|:root)/.test(base) ? base.replace(/^(html|:root)/, PRE) : PRE + ' ' + base;
  return ':where(' + inner + ')' + pseudo;
}

/* ---------- the three generated parts ---------- */
const SIZE = /^(-?[\d.]+)(px|em|rem|%|vw|vh|vmin|vmax|ch|ex)$/;
function sizeOfFont(v) {
  const t = splitTop(v.replace(/\s*\/\s*/g, ' / '), ' ').filter(Boolean);
  if (t.length === 1) return t[0] === 'inherit' ? 'inherit' : null;
  for (let i = 0; i < t.length; i++) {
    if (t[i] === '/') return t[i - 1];
    if (SIZE.test(t[i]) || /^(calc|clamp|min|max|var)\(/.test(t[i])) return t[i];
  }
  return null;
}
export function floorSize(v) {
  const m = SIZE.exec(v);
  if (m && m[2] === 'px') { const n = parseFloat(m[1]); return (n < 13 ? 12 : n < 15 ? 14 : n < 17 ? 16 : n) + 'px'; }
  if (m || /^(calc|clamp|min|max|var)\(/.test(v)) return 'max(12px, ' + v + ')';
  if (v === 'smaller') return 'max(12px, .83em)';
  return v;
}
/* the family inside a font shorthand: what follows the size (and its line height) */
function familyOfFont(v) {
  const t = splitTop(v.replace(/\s*\/\s*/g, ' / '), ' ').filter(Boolean);
  for (let i = 0; i < t.length; i++) {
    if (SIZE.test(t[i]) || /^(calc|clamp|min|max|var)\(/.test(t[i]) && !/^var\(--font/.test(t[i])) {
      const k = t[i + 1] === '/' ? i + 3 : i + 1;
      return k < t.length ? t.slice(k).join(' ').replace(/\s*,\s*/g, ', ') : null;
    }
  }
  return null;
}
/* mono stays only where the text is a key or a time (KS10.2): a kbd, a key, the band's clock, a time, a curfew, code; everything else reads in the text face */
const KEEP_MONO = /\bkbd\b|key|\btime\b|-time\b|band-clock|pp-clock|curfew|-when\b|\bcode\b|\.mono\b|-tlen|-td\b/;
const MONO = /mono/i;
const ACCENT = /var\(--(on-)?accent\)/;
function calmHover(prop, value) {
  if (prop === 'background' || prop === 'background-color') return 'var(--ui-sunk)';
  if (prop === 'color') return 'var(--ui-ink)';
  if (prop === 'box-shadow') return calmShadow(value.replace(/var\(--(on-)?accent\)/g, 'var(--ui-ink-faint)'));
  return value.replace(/var\(--(on-)?accent\)/g, 'var(--ui-ink-faint)');
}
const STILL = ':not([aria-pressed="true"], [aria-current="true"], [aria-current="page"], [aria-selected="true"], [aria-checked="true"], .on, .sel)';
/* the desk is flat and the hard offset shadow belongs to the Primary alone (in Night the old one is orange: --shadow-ink): a layer offset or
   blurred goes; an inset line (an active underline) and a ring (no offset, no blur) stay */
export function calmShadow(v) {
  const keep = splitTop(v, ',').map((x) => x.trim()).filter((layer) => {
    if (!layer || /\binset\b/.test(layer)) return true;
    const n = splitTop(layer, ' ').filter((t) => /^-?[\d.]+(px|em|rem)?$/.test(t)).map(parseFloat);
    return n.length >= 4 && n[0] === 0 && n[1] === 0 && n[2] === 0;
  });
  return keep.length ? keep.join(', ') : 'none';
}
export function generate() {
  const sizes = [], faces = [], hovers = [], shadows = []; let seq = 0;
  /* the browser's own small sizes, under every old rule (a type selector's weight, first in order): small, sub and sup are smaller, h5 and h6 .83em and .67em */
  for (const [sel, v] of [['small', 'smaller'], ['sub', 'smaller'], ['sup', 'smaller'], ['h5', '.83em'], ['h6', '.67em']]) sizes.push({ sel, w: weight(sel), o: -1, ctx: [], decl: 'font-size: ' + floorSize(v) });
  for (const f of OLD) {
    for (const r of parse(f === '@inline' ? inlineBlock() : read(f))) {
      if (r.ctx.some((x) => /^@media print\b/.test(x))) continue;
      let size = null, face = null, shadow = null; const hov = [];
      for (const d of r.decls) {
        if (d.important) continue;
        if (d.prop === 'box-shadow') shadow = d.value;
        if (d.prop === 'font-size') size = d.value;
        else if (d.prop === 'font-family') face = d.value.replace(/\s*,\s*/g, ', ');
        else if (d.prop === 'font') { const s = sizeOfFont(d.value), fam = familyOfFont(d.value); if (s) size = s; if (fam) face = fam; else if (d.value === 'inherit') face = 'inherit'; }
        if (ACCENT.test(d.value)) hov.push(d);
      }
      const o = seq++;
      for (const sel of r.sels) {
        if (SKIP.test(sel) || !onGm(sel)) continue;
        if (size !== null) sizes.push({ sel, w: weight(sel), o, ctx: r.ctx, decl: 'font-size: ' + floorSize(size) });
        if (shadow !== null) shadows.push({ sel, w: weight(sel), o, ctx: r.ctx, decl: 'box-shadow: ' + calmShadow(shadow) });
        if (face !== null && !PSEUDO.test(sel)) faces.push({ sel, w: weight(sel), o, ctx: r.ctx, decl: 'font-family: ' + (MONO.test(face) && !KEEP_MONO.test(sel) ? 'var(--ui-font-text)' : face) });
        if (hov.length && /:hover\b/.test(sel)) {
          const m = PSEUDO.exec(sel), still = m ? sel.slice(0, -m[1].length) + STILL + m[1] : sel + STILL;
          hovers.push({ sel: still, w: weight(sel), o, ctx: r.ctx, decl: hov.map((d) => d.prop + ': ' + calmHover(d.prop, d.value)).join('; ') });
        }
      }
    }
  }
  const emit = (list) => {
    list.sort((x, y) => cmp(x.w, y.w) || x.o - y.o);
    let out = '';
    /* one group per run of equal declarations: :where(<the root>) :where(<the old selectors>)<a pseudo-element>, zero weight; a selector whose
       subject is the root itself is written whole (it has no ancestor to match the root) */
    const key = (x) => { const m = PSEUDO.exec(x.sel), base = m ? x.sel.slice(0, -m[1].length) : x.sel, self = /^(html|:root)[^\s>+~]*$/.test(base);
      return { base, pseudo: m ? m[1] : '', self, k: x.decl + '|' + x.ctx.join('|') + '|' + (m ? m[1] : '') + '|' + self }; };
    for (let i = 0; i < list.length;) {
      let j = i; const e = key(list[i]);
      while (j < list.length && key(list[j]).k === e.k) j++;
      const group = list.slice(i, j).map(key);
      let rule = (e.self ? group.map((x) => scoped(x.base + x.pseudo)).join(',\n') : ':where(' + PRE + ') :where(' + group.map((x) => x.base).join(',\n  ') + ')' + e.pseudo) +
        ' { ' + list[i].decl + '; }';
      for (let k = list[i].ctx.length - 1; k >= 0; k--) rule = list[i].ctx[k] + ' {\n' + rule + '\n}';
      out += rule + '\n';
      i = j;
    }
    return out;
  };
  return BEGIN + '\n/* the type floor (KS10.2): every old font-size on the GM page, in the old order, floored and snapped to the scale */\n' + emit(sizes) +
    '/* mono for keys and the time alone (KS10.2): every old font family on the GM page, in the old order; mono becomes the text face unless the text is a key, a time or code */\n' + emit(faces) +
    '/* the shadow for the Primary alone: every old box-shadow on the GM page, in the old order; a hard offset (orange in Night) goes, an inset line or a ring stays */\n' + emit(shadows) +
    '/* no orange hover (KS10.3): an old hover that paints the accent paints the sunk ground and the ink, unless the control is pressed, current or on */\n' + emit(hovers) + END;
}
function current() {
  const css = fs.readFileSync(SKIN, 'utf8'), a = css.indexOf(BEGIN), b = css.indexOf(END);
  return a < 0 || b < 0 ? null : { css, a, b: b + END.length };
}

